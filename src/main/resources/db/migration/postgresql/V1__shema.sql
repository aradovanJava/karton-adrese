-- Karton adrese – shema za PostgreSQL + PostGIS
-- Koordinate se spremaju kao lat/lon (WGS84), a PostGIS geometrija nastaje automatski
-- (generirani stupac) i ima prostorni indeks za upite tipa "sve unutar 800 m".

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE izvor (
    id                 VARCHAR(80) PRIMARY KEY,
    naziv              VARCHAR(300) NOT NULL,
    izdavatelj         VARCHAR(200),
    licenca            VARCHAR(120),
    poveznica          VARCHAR(600),
    vrsta              VARCHAR(30),
    status             VARCHAR(20) NOT NULL DEFAULT 'NIJE_PREUZETO',
    poruka             TEXT,
    zadnje_preuzimanje TIMESTAMP,
    datum_podatka      DATE,
    procitano          INTEGER,
    spremljeno         INTEGER,
    bez_lokacije       INTEGER,
    geokodirano        INTEGER,
    izvan_podrucja     INTEGER
);

CREATE TABLE poi (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    izvor_id   VARCHAR(80)  NOT NULL REFERENCES izvor (id),
    kategorija VARCHAR(30)  NOT NULL,
    naziv      VARCHAR(400) NOT NULL,
    adresa     VARCHAR(400),
    lat        DOUBLE PRECISION NOT NULL,
    lon        DOUBLE PRECISION NOT NULL,
    atributi   TEXT,
    azurirano  DATE,
    geom       geometry(Point, 4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lon, lat), 4326)) STORED
);
CREATE INDEX poi_lat_lon ON poi (lat, lon);
CREATE INDEX poi_kategorija ON poi (kategorija);
CREATE INDEX poi_izvor ON poi (izvor_id);
CREATE INDEX poi_geom ON poi USING GIST (geom);

CREATE TABLE stajaliste (
    id        VARCHAR(80) PRIMARY KEY,
    naziv     VARCHAR(200) NOT NULL,
    lat       DOUBLE PRECISION NOT NULL,
    lon       DOUBLE PRECISION NOT NULL,
    linije    VARCHAR(600),
    tramvaj   BOOLEAN NOT NULL DEFAULT FALSE,
    autobus   BOOLEAN NOT NULL DEFAULT FALSE,
    polazaka  INTEGER NOT NULL DEFAULT 0,
    geom      geometry(Point, 4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lon, lat), 4326)) STORED
);
CREATE INDEX stajaliste_lat_lon ON stajaliste (lat, lon);
CREATE INDEX stajaliste_geom ON stajaliste USING GIST (geom);

CREATE TABLE celija (
    id          VARCHAR(60) PRIMARY KEY,
    lat         DOUBLE PRECISION NOT NULL,
    lon         DOUBLE PRECISION NOT NULL,
    stanovnika  INTEGER,
    indeks15    INTEGER,
    nedostaje   VARCHAR(300),
    izracunato  TIMESTAMP,
    geom        geometry(Point, 4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lon, lat), 4326)) STORED
);
CREATE INDEX celija_geom ON celija USING GIST (geom);

CREATE TABLE adresa (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv          VARCHAR(300) NOT NULL,
    naziv_norm     VARCHAR(300) NOT NULL UNIQUE,
    lat            DOUBLE PRECISION NOT NULL,
    lon            DOUBLE PRECISION NOT NULL,
    gradska_cetvrt VARCHAR(150),
    mjesni_odbor   VARCHAR(150),
    izvor          VARCHAR(80),
    azurirano      TIMESTAMP
);
CREATE INDEX adresa_norm ON adresa (naziv_norm varchar_pattern_ops);

CREATE TABLE ulica (
    naziv_norm VARCHAR(200) PRIMARY KEY,
    naziv      VARCHAR(200) NOT NULL
);
CREATE INDEX ulica_norm ON ulica (naziv_norm varchar_pattern_ops);

CREATE TABLE granica (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vrsta   VARCHAR(20)  NOT NULL, -- GRADSKA_CETVRT ili MJESNI_ODBOR
    naziv   VARCHAR(200) NOT NULL,
    geojson TEXT         NOT NULL
);

CREATE TABLE postaja_zraka (
    id            VARCHAR(60) PRIMARY KEY,
    naziv         VARCHAR(200) NOT NULL,
    mreza         VARCHAR(200),
    lat           DOUBLE PRECISION NOT NULL,
    lon           DOUBLE PRECISION NOT NULL,
    godina        INTEGER,
    prosjek_pm10  DOUBLE PRECISION,
    dana_iznad_50 INTEGER,
    izvor         VARCHAR(300),
    geom          geometry(Point, 4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lon, lat), 4326)) STORED
);

CREATE TABLE prijava (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objekt  VARCHAR(400)  NOT NULL,
    izvor   VARCHAR(300),
    adresa  VARCHAR(300),
    opis    VARCHAR(2000) NOT NULL,
    email   VARCHAR(200),
    vrijeme TIMESTAMP     NOT NULL,
    status  VARCHAR(20)   NOT NULL DEFAULT 'NOVA'
);
